export type IconName = keyof typeof PATHS

export function Icon({ name, size = 22, title }: { name: IconName; size?: number; title?: string }) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" aria-hidden={title ? undefined : true} role={title ? 'img' : undefined}>
      {title ? <title>{title}</title> : null}
      <path d={PATHS[name]} fill="currentColor" />
    </svg>
  )
}

export function IconButton({
  icon,
  label,
  onClick,
  active,
  disabled,
  showLabel,
  title,
  text,
  kbd,
  className,
}: {
  icon: IconName
  label: string
  /** Tooltip, when it should say more than the label */
  title?: string
  onClick?: () => void
  active?: boolean
  disabled?: boolean
  showLabel?: boolean
  /** Visible text when it should be shorter than the label (implies showLabel) */
  text?: string
  /** Keyboard shortcut shown next to the visible text */
  kbd?: string
  className?: string
}) {
  return (
    <button
      type="button"
      className={`icon-btn${active ? ' active' : ''}${showLabel ? ' labeled' : ''}${text ? ' texted' : ''}${className ? ` ${className}` : ''}`}
      onClick={onClick}
      disabled={disabled}
      title={title ?? label}
      aria-label={label}
      aria-pressed={active === undefined ? undefined : active}
    >
      <Icon name={icon} />
      {showLabel || text ? <span className="btn-text">{text ?? label}</span> : null}
      {kbd ? <kbd className="btn-kbd">{kbd}</kbd> : null}
    </button>
  )
}
